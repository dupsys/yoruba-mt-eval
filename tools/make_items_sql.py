"""Build the SQL that loads evaluation items into Supabase, from the rater workbooks (never from the answer keys).

Writes eval_dashboard/private/items_<package>.sql (git-ignored: it contains test sentences) to paste into the
Supabase SQL editor, plus private/raters_template.sql for registering evaluators. No secret key is needed.

Usage (project root):
  .venv/bin/python eval_dashboard/tools/make_items_sql.py            # focused package only (recommended)
  .venv/bin/python eval_dashboard/tools/make_items_sql.py --full     # also the full workbook (300 items)
"""
import sys
import unicodedata
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
HE = ROOT / "reports" / "human_eval"
PRIVATE = Path(__file__).resolve().parents[1] / "private"
PACKAGES = {"focus": HE / "menyo_focus_afrique_vs_nllb13.xlsx", "full": HE / "menyo_human_eval.xlsx"}


def q(v) -> str:
    """SQL string literal (dollar-quoting avoids any escaping problems with quotes in sentences)."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "null"
    s = unicodedata.normalize("NFC", str(v))
    tag = "$y$"
    assert tag not in s
    return f"{tag}{s}{tag}"


def build(package: str, path: Path) -> Path:
    df = pd.read_excel(path, sheet_name="Evaluation", dtype=str)
    if any("key" in c.lower() or "system" in c.lower() for c in df.columns):
        raise SystemExit(f"{path.name} looks like an answer key; refusing to load it")
    lines = [f"-- {len(df)} items from {path.name} (package '{package}'); generated by tools/make_items_sql.py",
             "-- Paste into Supabase > SQL Editor and run. Safe to re-run: existing items are updated.",
             "begin;"]
    for pos, r in enumerate(df.itertuples(index=False), start=1):
        vals = [r[0], package, pos, r[1], r[2], r[3], r[4], r[5], r[6]]
        lines.append("insert into public.items (item_id, package, position, comparison, direction, domain, source, "
                     "output_a, output_b) values (" + ", ".join(q(v) if not isinstance(v, int) else str(v) for v in vals)
                     + ") on conflict (item_id) do update set package = excluded.package, position = excluded.position, "
                     "source = excluded.source, output_a = excluded.output_a, output_b = excluded.output_b;")
    lines.append("commit;")
    out = PRIVATE / f"items_{package}.sql"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{out}: {len(df)} items")
    return out


def main():
    PRIVATE.mkdir(exist_ok=True)
    build("focus", PACKAGES["focus"])
    if "--full" in sys.argv:
        build("full", PACKAGES["full"])
    (PRIVATE / "raters_template.sql").write_text(
        "-- Register evaluators (one row each). Use lower-case emails and codes such as R01, R02, ...\n"
        "-- Make yourself an admin so you can see progress and export ratings.\n"
        "insert into public.raters (email, rater_code, is_admin) values\n"
        "  ('organiser@example.org', 'ADM', true),\n"
        "  ('rater1@example.org', 'R01', false),\n"
        "  ('rater2@example.org', 'R02', false),\n"
        "  ('rater3@example.org', 'R03', false)\n"
        "on conflict (email) do nothing;\n"
        "-- To stop someone's access later:  update public.raters set active = false where rater_code = 'R02';\n",
        encoding="utf-8")
    print(f"{PRIVATE / 'raters_template.sql'} written (edit the emails before running)")


if __name__ == "__main__":
    main()
