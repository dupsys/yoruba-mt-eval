"""Build Task 2 (proverb meanings) items for the dashboard from the proverb benchmark's T2 runs.

One item per (proverb, model, condition) on the original (fully marked) collection test proverbs. Items are
shuffled with a fixed seed so that explanations of the same proverb are never adjacent; which model and condition
wrote each explanation goes ONLY into the offline answer key. Empty explanations (e.g. reasoning that hit its
token limit) are not shown; they are listed in the key as not rated and already count as failures.

Usage (project root):  .venv/bin/python eval_dashboard/tools/make_meaning_items.py
Writes eval_dashboard/private/meaning_items.sql   (paste into the Supabase SQL editor after migration 004)
       reports/proverbs/human_meaning/meaning_KEY.csv  (never upload; never show raters)
"""
from __future__ import annotations

import hashlib
import random
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
RUNS = ROOT / "results/proverbs/coll_test_orig"
OUT_SQL = ROOT / "eval_dashboard/private/meaning_items.sql"
OUT_KEY = ROOT / "reports/proverbs/human_meaning/meaning_KEY.csv"
MODELS, CONDS, SEED = ("gemma4", "qwen35"), ("direct", "think"), 20261121


def q(s: str) -> str:
    tag = "$m$"
    assert tag not in s
    return f"{tag}{s}{tag}"


def main():
    coll = pd.read_csv(ROOT / "data/proverb_bench/coll_test_orig.csv", dtype=str, keep_default_na=False)
    rows = []
    for m in MODELS:
        for c in CONDS:
            p = RUNS / f"meaning_{m}" / c / "predictions_yo-en.csv"
            if not p.exists():
                raise SystemExit(f"missing {p}: run the T2 meaning task for {m}/{c} first")
            d = pd.read_csv(p, dtype=str, keep_default_na=False)
            assert d.id.tolist() == coll.row_id.tolist()
            for (_, pr), h, st in zip(coll.iterrows(), d.hypothesis, d.status):
                rows.append({"proverb_id": pr.row_id, "proverb": pr.yoruba, "literal": pr.english,
                             "stated_meaning": pr.wisdom, "explanation": h.strip(), "model": m, "condition": c,
                             "status": st})
    df = pd.DataFrame(rows)
    shown = df[df.explanation != ""].copy()
    # shuffle; then repair any adjacent pair of the same proverb by swapping with a later item
    rng = random.Random(SEED)
    idx = list(shown.index)
    rng.shuffle(idx)
    for i in range(1, len(idx)):
        if shown.at[idx[i], "proverb_id"] == shown.at[idx[i - 1], "proverb_id"]:
            for j in range(i + 1, len(idx)):
                ok_here = shown.at[idx[j], "proverb_id"] != shown.at[idx[i - 1], "proverb_id"]
                ok_there = (j + 1 >= len(idx) or shown.at[idx[i], "proverb_id"] != shown.at[idx[j + 1], "proverb_id"]) and \
                           shown.at[idx[i], "proverb_id"] != shown.at[idx[j - 1], "proverb_id"]
                if ok_here and ok_there:
                    idx[i], idx[j] = idx[j], idx[i]
                    break
    shown = shown.loc[idx].reset_index(drop=True)
    shown["item_id"] = [f"M{i + 1:03d}" for i in range(len(shown))]
    shown["position"] = range(1, len(shown) + 1)
    adjacent = int((shown.proverb_id == shown.proverb_id.shift()).sum())
    OUT_SQL.parent.mkdir(parents=True, exist_ok=True)
    OUT_KEY.parent.mkdir(parents=True, exist_ok=True)
    lines = ["-- Task 2 items (generated by tools/make_meaning_items.py). Run AFTER migrations/004_meaning_task.sql.",
             "insert into public.meaning_items(item_id, position, proverb, literal, stated_meaning, explanation) values"]
    vals = [f"({q(r.item_id)}, {r.position}, {q(r.proverb)}, {q(r.literal)}, {q(r.stated_meaning)}, {q(r.explanation)})"
            for r in shown.itertuples()]
    lines.append(",\n".join(vals))
    lines.append("on conflict (item_id) do update set position = excluded.position, proverb = excluded.proverb, "
                 "literal = excluded.literal, stated_meaning = excluded.stated_meaning, explanation = excluded.explanation;")
    lines.append("select count(*) as meaning_items_loaded from public.meaning_items;")
    OUT_SQL.write_text("\n".join(lines) + "\n", encoding="utf-8")
    key = pd.concat([shown[["item_id", "position", "proverb_id", "model", "condition", "status"]],
                     df[df.explanation == ""][["proverb_id", "model", "condition", "status"]].assign(
                         item_id="", position="", note="empty explanation: not rated (counted as failure)")])
    key.to_csv(OUT_KEY, index=False)
    print(f"items: {len(shown)} shown, {int((df.explanation == '').sum())} empty not shown; adjacent same-proverb pairs: "
          f"{adjacent}; sql sha256 {hashlib.sha256(OUT_SQL.read_bytes()).hexdigest()[:16]}")


if __name__ == "__main__":
    main()
